use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// An [EvdevConfig] defines a matching evdev input event
#[derive(Debug, Deserialize, Serialize, Clone, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case")]
pub struct EvdevConfig {
    pub event_type: EventType,
    pub event_code: EventCode,
    pub event_value: Option<u16>,
    pub value_type: ValueType,
    pub axis_direction: Option<AxisDirection>,
}

#[derive(Debug, Deserialize, Serialize, Clone, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum ValueType {
    Button,
    Trigger,
    JoystickX,
    JoystickY,
    ImuX,
    ImuY,
    ImuZ,
}

/// The AxisDirection can be used to map one half of an axis to a particular
/// capability. For example, you can map the negative values of `ABS_Y` to the
/// `DPadDown` capability and the positive values of `ABS_Y` to `DPadUp`.
#[derive(Debug, Deserialize, Serialize, Clone, JsonSchema, PartialEq)]
#[serde(rename_all = "snake_case")]
pub enum AxisDirection {
    None,
    Positive,
    Negative,
}

#[derive(Debug, Deserialize, Serialize, Clone, JsonSchema, PartialEq, Copy)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum EventType {
    /// A bookkeeping event. Usually not important to applications.
    Sync = 0x00,
    /// A key changed state. A key, or button, is usually a momentary switch (in the circuit sense). It has two
    /// states: down, or up. There are events for when keys are pressed (become down) and
    /// released (become up). There are also "key repeats", where multiple events are sent
    /// while a key is down.
    Key = 0x01,
    /// Movement on a relative axis. There is no absolute coordinate frame, just the fact that
    /// there was a change of a certain amount of units. Used for things like mouse movement or
    /// scroll wheels.
    Rel = 0x02,
    /// Movement on an absolute axis. Used for things such as touch events and joysticks.
    Abs = 0x03,
    /// Miscellaneous events that don't fall into other categories. For example, Key presses may
    /// send `MSC_SCAN` events before each KEY event
    Msc = 0x04,
    /// Change in a switch value. Switches are boolean conditions and usually correspond to a
    /// toggle switch of some kind in hardware.
    Sw = 0x05,
    /// An LED was toggled.
    Led = 0x11,
    /// A sound was made.
    Snd = 0x12,
    /// Metadata about key repeat configuration.
    Rep = 0x14,
    /// Sent to the device with a previusly obtained effect id as a code in order to toggle the effect.
    Ff = 0x15,
    /// Used to trigger power events such as suspend or power off.
    Pwr = 0x16,
    /// A force feedback effect's state changed.
    FfStatus = 0x17,
    /// An event originating from uinput.
    Uinput = 0x0101,
}

impl EventType {
    pub fn as_u16(&self) -> u16 {
        *self as u16
    }
}

/// An evdev event code, either a named kernel define or a raw code value
/// for codes with no kernel define.
#[derive(Debug, Deserialize, Serialize, Clone, JsonSchema, PartialEq)]
#[serde(untagged)]
pub enum EventCode {
    /// A named kernel event code, e.g. `BTN_TRIGGER`.
    Named(NamedEventCode),
    /// A raw code value, e.g. `0x12c`.
    Raw(u16),
}

impl EventCode {
    pub fn as_u16(&self) -> u16 {
        match self {
            Self::Named(code) => code.as_u16(),
            Self::Raw(code) => *code,
        }
    }
}

